#!/usr/bin/env python3
"""mkqtf2.py -- writes qtf2's instance units (qtf2_inst_a<KA>.cu, one per KA) and the instance table (qtf2_table.inc).
Menu (user, 2026-11-01): 1/8 steps K0.125-2.875 (KA 0-2, all seven even masks), quarters K3.25-4.75 (KA 3-4),
halves K5.5-7.5 (KA 5-7). Masks: the fork's canonical frac_mask(n), n = 16 x the fractional part."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
def frac_mask(n): return sum(1 << i for i in range(16) if ((i + 1) * n) // 16 - (i * n) // 16)
MENU = {0: range(2, 16, 2), 1: range(2, 16, 2), 2: range(2, 16, 2), 3: range(2, 16, 2), 4: range(2, 16, 2), 5: (4, 8, 12), 6: (4, 8, 12), 7: (4, 8, 12)}
# 2026-11-02 (user): 1/8 steps up to K4.875, quarters K5.25-6.75 (i8 to K7), quarters to K7.75 (plain codebook K6-8, user)
# KA 5 quarters (K5.25 / 5.75): head donors only (headremake.sh), the trunk ladder stops at K5.5 / 6
# integer K1-4 (MASK 0): the same search as exllamav3's integer kernel; qtf2int6check.py tests identity / speed, and
# integer levels run here only where it is identical and faster
for ka in (1, 2, 3, 4): MENU[ka] = (0,) + tuple(MENU[ka])
for ka in (5, 6, 7): MENU[ka] = (0,) + tuple(MENU[ka])   # integer K5-7 on qtf2 (K5: only if v9 makes it faster)
rows = []
for ka, ns in MENU.items():
    # v9 (bench 2026-11-02): KA 6-7 mixed-rate kernels take QTF2_HIOPT (inlined forward, bounded unroll: x1.4-6), the
    # rest are faster without it -> mixed KA >= 6 instances go to their own unit (qtf2_inst_a<ka>f.cu) built with it
    if ka >= 6 and any(n for n in ns):
        fb = [f'// generated by mkqtf2.py: qtf2 mixed-rate instances for KA = {ka}, with QTF2_HIOPT', '#define QTF2_HIOPT',
              '#include "qtf2_types.cuh"', '#include "qtf2.cuh"', '']
        for n in [n for n in ns if n]:
            m = frac_mask(n)
            fb.append(f'fp_qtf2 qtf2_a{ka}_m{m:04x}() {{ return qtf2_kernel<{ka}, 0x{m:04x}u>; }}')
            rows.append((ka, m))
        open(f"{HERE}/qtf2_inst_a{ka}f.cu", "w").write("\n".join(fb) + "\n")
        ns = [n for n in ns if not n]
    body = [f'// generated by mkqtf2.py: qtf2 instances for KA = {ka}', '#include "qtf2_types.cuh"', '#include "qtf2.cuh"', '']
    for n in ns:
        m = frac_mask(n)
        body.append(f'fp_qtf2 qtf2_a{ka}_m{m:04x}() {{ return qtf2_kernel<{ka}, 0x{m:04x}u>; }}')
        rows.append((ka, m))
    open(f"{HERE}/qtf2_inst_a{ka}.cu", "w").write("\n".join(body) + "\n")
decl = "".join(f"fp_qtf2 qtf2_a{ka}_m{m:04x}();\n" for ka, m in rows)
tab = "".join(f"    {{{ka}, 0x{m:04x}u, &qtf2_a{ka}_m{m:04x}, Qtf2Geom<{ka}>::nt, Qtf2Geom<{ka}>::shmem}},\n" for ka, m in rows)
open(f"{HERE}/qtf2_table.inc", "w").write("// generated by mkqtf2.py\n" + decl +
    "static const Qtf2Entry qtf2_table[] = {\n" + tab + "};\n")
print(len(rows), "instances")
