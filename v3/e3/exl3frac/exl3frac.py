"""exl3frac -- the V3 menu's fractional rates (quarter steps to K5, half steps to K8) on the prebuilt exllamav3 1.6.3.

exllamav3's fractional quantizer kernel is generic in its step mask, but the build only instantiates 0xAAAA for KA 1-3.
Branch rxm-frac-quarter (quantize/exl3-patches/0002) adds the menu's instances; rebuilding the whole extension for that
is slow, so this builds just quantize_tiles_frac (frac_bind.cu, generated by mkbind.py) plus the fork's per-KA
instance units as a side extension, with exllamav3's own compiler flags, and install() swaps it in:
  - quantize.ext.quantize_tiles_frac -> the side extension (every other ext call goes to the prebuilt one; its
    pack/unpack_trellis_frac already take any KA 1-7 / 16-bit mask)
  - quantize.frac_k -> canonical even masks for K = KA + n/16, n even (the prebuilt one asserts half-integers)
Use: import exl3frac; exl3frac.install(SRC)  with SRC = <fork>/exllamav3/exllamav3_ext, before quantizing.
Env: TORCH_EXTENSIONS_DIR (default <here>/build), PYTORCH_ROCM_ARCH (e.g. gfx1201), MAX_JOBS."""
import glob, os


def frac_mask(n: int) -> int:
    """bit i set when step i carries the extra bit: floor((i + 1) n / 16) - floor(i n / 16) = 1 (4: 0x8888, 8: 0xAAAA)"""
    return sum(1 << i for i in range(16) if ((i + 1) * n) // 16 - (i * n) // 16)


def frac_k(K):
    """(KA, MASK) for K = KA + n / 16 (n even, KA >= 1); None for integer K. Same as the fork's frac_k."""
    if isinstance(K, int) or float(K).is_integer():
        return None
    ka = int(K)
    n = (K - ka) * 16
    assert ka >= 1 and abs(n - round(n)) < 1e-9 and round(n) % 2 == 0, \
        f"fractional bitrate {K}: need KA >= 1 and K = KA + n / 16 with n even"
    return ka, frac_mask(round(n))


def load(src: str, verbose: bool = False):
    import torch
    from torch.utils import cpp_extension as C
    from exllamav3.util import cuda_flags as F
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.abspath(src)
    os.environ.setdefault("TORCH_EXTENSIONS_DIR", os.path.join(here, "build"))
    hip = bool(torch.version.hip)
    cflags, cuda = ["-O3"], F.cuda_cflags(cuda_home=C.CUDA_HOME, hip=hip)
    if hip:
        assert os.environ.get("PYTORCH_ROCM_ARCH"), "set PYTORCH_ROCM_ARCH (e.g. gfx1201)"
        F.use_rocm_sdk_devel(C)
        inc = F.hip_include_flags(src)
        cflags += inc; cuda += inc
        F.patch_hip_ninja_file_writer(C)
    units = sorted(glob.glob(f"{src}/quant/comp_units/quantize_tiles_frac_inst_a*.cu"))
    assert len(units) == 7, f"expected the fork's 7 per-KA instance units under {src}, found {len(units)}"
    return C.load(name="exl3frac", sources=[os.path.join(here, "frac_bind.cu")] + units,
                  extra_include_paths=[os.path.join(src, "quant"), src], extra_cflags=cflags,
                  extra_cuda_cflags=cuda, extra_ldflags=["-lhipblas"] if hip else [], verbose=verbose)


class _Ext:
    """the prebuilt extension, with quantize_tiles_frac taken from exl3frac"""
    def __init__(self, base, frac): self._base, self._frac = base, frac
    def __getattr__(self, name): return getattr(self._frac if name == "quantize_tiles_frac" else self._base, name)


def install(src: str, verbose: bool = False):
    import exllamav3.modules.quant.exl3_lib.quantize as Q
    if isinstance(Q.ext, _Ext): return Q
    Q.ext = _Ext(Q.ext, load(src, verbose))
    Q.frac_k = frac_k
    return Q
