#!/usr/bin/env python3
"""gen_tables.py > tables.h -- constants and tables of the cb208 codebook bench (w208).

* fixed-point maps bytesum -> grid index for the rounded computed codes (mul1_i8, int4grid, qtip_1mad): the device
  computes n = (bs * MUL + ADD) >> SH; searched here so that it equals the float definition (v3/e3/trellis.py
  `codebook`, np.round) for every byte sum 0..1020. The bench re-derives the float definition on the host and checks
  all 65,536 states against the device, so a wrong fit cannot pass.
* qtip_3inst's f32 scale to the int8 grid (127 / (3.5 sd)).
* CPTC tables for the unified L=16 pair (0x9282, 0xA981), INT8 storage, scale 32 (paper Table 17): the Eq. (2)
  conditional-mean start table rescaled by (1 + 2/n)(1 - 4^-K), n = 17 - K (cptc/cptc.py table_init_gauss), no Lloyd
  rounds: decode time does not depend on the table contents, the bench only needs fixed, documented bytes.
  One table per ceil(K) in 1..4:  T6 (Q=6 lower half, 64 signed entries, mirror fold), T6F (Q=6 in full, 127),
  T5 (Q=5 in full, 63), TLC (one multiply a1, 64 cells), ST10 / ST12 (state tables, 2^L entries indexed by the low L
  state bits; the cell order is a fixed odd-multiplier permutation of the Gaussian quantiles).
"""
import numpy as np
from scipy.stats import norm

A0, A1 = 0x9282, 0xA981
s = np.arange(65536, dtype=np.uint64)


def bytesum(h):
    return sum(((h >> np.uint64(8 * i)) & np.uint64(0xFF)) for i in range(4)).astype(np.int64)


def fit(bs_all, target, name, lo=None, hi=None):
    """target[bs] for bs in 0..1020 (float def) -> MUL, ADD, SH with ((bs*MUL + ADD) >> SH) == target (after clamp)."""
    bs = np.arange(1021, dtype=np.int64)
    slope = np.polyfit(bs[200:800], target[200:800].astype(np.float64), 1)
    for sh in range(12, 22):
        for dm in (0, -1, 1, -2, 2):
            mul = int(round(slope[0] * (1 << sh))) + dm
            if mul <= 0 or mul * 1020 >= 1 << 31:
                continue
            # the admissible ADD interval from every bs (unclamped ones): target <= (bs mul + add) / 2^sh < target + 1
            ok = np.ones(1021, bool) if lo is None else (target > lo) & (target < hi)
            amin = int(np.max((target[ok] << sh) - bs[ok] * mul)); amax = int(np.min(((target[ok] + 1) << sh) - bs[ok] * mul)) - 1
            for add in ((amin + amax) // 2, amin, amax):
                if amin > amax:
                    break
                v = (bs * mul + add) >> sh
                if lo is not None:
                    v = np.clip(v, lo, hi)
                if np.array_equal(v, target):
                    return mul, add, sh
    raise SystemExit(f"no fit for {name}")


out = ["// generated by gen_tables.py -- do not edit", "#pragma once", "#include <cstdint>"]

# mul1 family (trellis.py): standardised byte sum of s * 0x83DCD12D
h = (s * np.uint64(0x83DCD12D)) & np.uint64(0xFFFFFFFF)
bsm = bytesum(h)
mean, sd = bsm.mean(), bsm.astype(np.float64).std()
bs = np.arange(1021, dtype=np.float64)
v = (bs - mean) / sd
t = np.clip(np.round(v / (3.5 / 127)), -127, 127).astype(np.int64) + 128
assert t.min() > 0 and t.max() < 255
m, a, sh = fit(bsm, t, "mul1_i8")
out.append(f"#define MUL1I8_MUL {m}u\n#define MUL1I8_ADD {a}u\n#define MUL1I8_SH {sh}")
t = (np.clip(np.round(v / (2.6 / 7.5) - 0.5) + 0.5, -7.5, 7.5) + 7.5).astype(np.int64)
m, a, sh = fit(bsm, t, "int4grid", 0, 15)
out.append(f"#define I4G_MUL {m}\n#define I4G_ADD ({a})\n#define I4G_SH {sh}")

# qtip 1mad: (bytesum(s * 34038481 + 76625530) - 510) / 147.800537109375, on the int8 grid (+-127 = 3.5 sd)
v = (bs - 510) / 147.800537109375
t = np.clip(np.round(v / (3.5 / 127)), -127, 127).astype(np.int64) + 128
assert t.min() > 0 and t.max() < 255
m, a, sh = fit(None, t, "qtip_1mad")
out.append(f"#define Q1MAD_MUL {m}u\n#define Q1MAD_ADD {a}u\n#define Q1MAD_SH {sh}")

# qtip 3inst: fp16 + fp16 (half arithmetic), standardised, int8 grid
x = (s * np.uint64(89226354) + np.uint64(64248484)) & np.uint64(0xFFFFFFFF)
mask = ((1 << 15) + (1 << 12) - 1); mask = (mask << 16) + mask
res = ((x & np.uint64(mask)) ^ np.uint64(996162400)).astype(np.uint32)
top = (res >> 16).astype(np.uint16).view(np.float16)
bot = (res & 0xFFFF).astype(np.uint16).view(np.float16)
r = (top + bot).astype(np.float32)
sd3 = float(r.astype(np.float64).std())
c = np.float32(127 / (3.5 * sd3))
q = np.rint(r * c)
out.append(f"// qtip_3inst: sd {sd3:.6f}, grid range [{int(q.min())}, {int(q.max())}]")
out.append(f"#define Q3INST_C {float(c).hex()}f\n#define Q3INST_CLAMP {int(q.min() < -127 or q.max() > 127)}")


def eq2(idx, ncell, K, perm=None):
    hcnt = np.bincount(idx, minlength=ncell).astype(np.float64)
    if perm is not None:
        hcnt = hcnt[np.argsort(perm)]          # cells in quantile order
    G = np.cumsum(hcnt) / hcnt.sum()
    lo, hi = np.concatenate([[0.0], G[:-1]]), G
    a, b = norm.ppf(lo), norm.ppf(hi)
    with np.errstate(invalid="ignore", divide="ignore"):
        T = np.where(hi > lo, (norm.pdf(a) - norm.pdf(b)) / (hi - lo), 0.0)
    T *= (1 + 2 / (16 - K + 1)) * (1 - 4.0 ** -K)
    if perm is not None:
        T = T[perm]
    return T


def i8(T):
    return np.clip(np.round(32 * T), -127, 127).astype(np.int64)


def emit(name, rows, signed):
    ty = "int8_t" if signed else "uint8_t"
    n = len(rows[0])
    out.append(f"static const {ty} {name}[4][{n}] = {{")
    for r in rows:
        out.append("  {" + ",".join(str(int(x)) for x in r) + "},")
    out.append("};")


x0, x1 = (s * np.uint64(A0)) & np.uint64(0xFFFF), (s * np.uint64(A1)) & np.uint64(0xFFFF)
i6 = ((x0 >> np.uint64(10)) + (x1 >> np.uint64(10))).astype(np.int64)
i5 = ((x0 >> np.uint64(11)) + (x1 >> np.uint64(11))).astype(np.int64)
ilc = (x1 >> np.uint64(10)).astype(np.int64)
T6, T6F, T5, TLC, ST10, ST12 = [], [], [], [], [], []
for K in (1, 2, 3, 4):
    f = eq2(i6, 127, K)
    low = np.zeros(64); low[:63] = (f[:63] - f[126:63:-1]) / 2
    low = i8(low)
    T6.append(low)
    full = np.concatenate([low[:64], -low[62::-1]])     # the fold, stored out: full[i] = i < 64 ? low[i] : -low[126 - i]
    assert len(full) == 127
    T6F.append(full + 128)
    T5.append(np.concatenate([i8(eq2(i5, 63, K)) + 128, [128]]))
    TLC.append(i8(eq2(ilc, 64, K)) + 128)
    for L, dst in ((10, ST10), (12, ST12)):
        n = 1 << L
        perm = (np.arange(n) * 0x9E5 + 0x1F3) % n          # state-table cell j holds quantile cell perm[j]
        dst.append(i8(eq2(np.arange(n), n, K, perm)) + 128)
out.append(f"#define CPTC_A0 0x{A0:04X}u\n#define CPTC_A1 0x{A1:04X}u")
emit("T6", T6, True); emit("T6F", T6F, False); emit("T5", T5, False); emit("TLC", TLC, False)
emit("ST10", ST10, False); emit("ST12", ST12, False)
print("\n".join(out))
