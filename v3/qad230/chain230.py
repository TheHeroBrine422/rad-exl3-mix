"""chain230.py (box2, started by run230.sh, which holds the four card locks) -- w230: the teacher sets t1 (agent cuts, whole prefixes) and
t2 (chat at varied settings), generated by IQ6R-V4 and labelled by bf16 goldens, as two LANES that work-steal:
  lane A = cards 0,1 (server port 8020), lane B = cards 2,3 (port 8021); a lane is either a TP2 generation server or a TP2 bf16 recorder.
  Both lanes generate set 2 (judge + train; sessions are claimed, gen230.py). Lane A then waits for set 2's tail, builds its documents
  and records them (chunks, TP2, bf16 KV, top-512) while lane B starts set 1; lane A joins set 1 when its set-2 chunks are recorded.
  A lane that has nothing left to claim in set 1 helps with unrecorded chunks, then (all of set 1 generated) both lanes record set 1's
  chunks, the deepest first. A chunk that fails on TP2 (a deep document that does not fit 2 x 32 GB: bf16 weights 27 GB a card) is
  retried at the end on all four cards (TP4). Finished chunks of a set are merged (merge230.py) and checked (check230.py) at once.
Restartable: every step is skipped when its output exists (cut files, gen.done, docs, chunk goldens, merged goldens); a restart clears
the claim files. Log: W/chain.log (CT); a progress line every 10 minutes."""
import collections, json, os, shutil, subprocess, sys, threading, time, urllib.request

Q = "/data/q27"; E = os.environ.get                                                           # W230_* overrides: the no-GPU test (chaintest230.py)
QROOT = E("W230_QROOT", Q + "/queue"); W = E("W230_ROOT", Q + "/teach230"); C = E("W230_CODE", W + "/code/v3/qad230"); PY = E("W230_PY", Q + "/venv/bin/python")
LIBS = "/opt/rocm-10.1/lib:/data/q27/ffmpeg-libs"
GEN_RB, GEN_RH = E("W230_GEN_RB", Q + "/w216/install/bin/radiance"), Q + "/w216/install/share/radiance"      # the generation build (w228's serve.sh)
REC_RB, REC_RH = E("W230_REC_RB", Q + "/w206/install/bin/radiance"), Q + "/w206/install/share/radiance"      # the queue's recording build (qenv.sh box2)
IQ6R = Q + "/onpol/iq6r/qwen3.8-27b-iq6r-v4.rad"; MODEL = E("W230_MODEL", Q + "/models/qwen38-27b-bf16")
LANES = {"A": ("0,1", int(E("W230_PORT_A", 8020))), "B": ("2,3", int(E("W230_PORT_B", 8021)))}
SETS = {
    "t2-judge": dict(target=0, chunks=1, final=QROOT + "/slices/golden-jt2", corpus_out=QROOT + "/slices/golden-jt2.jsonl", mask=None),
    "t2": dict(target=2_000_000, chunks=2, final=QROOT + "/ext/gold/tset2", corpus_out=QROOT + "/ext/teach230/tset2.jsonl", mask=QROOT + "/ext/genmask/tset2.u8"),
    "t1-judge": dict(target=0, chunks=1, final=QROOT + "/slices/golden-jt1", corpus_out=QROOT + "/slices/golden-jt1.jsonl", mask=None),
    "t1": dict(target=2_000_000, chunks=10, final=QROOT + "/ext/gold/tset1", corpus_out=QROOT + "/ext/teach230/tset1.jsonl", mask=QROOT + "/ext/genmask/tset1.u8"),
}
GEN_SLOTS = {"t2-judge": 3, "t2": 9, "t1-judge": 2, "t1": 10}
ABORT = threading.Event(); LOCK = threading.Lock()


def log(s):
    with LOCK, open(f"{W}/chain.log", "a") as f: f.write(f"{time.strftime('%m-%d %-I:%M %p CST', time.localtime())} {s}\n")


def render(n): return f"{W}/render-{n}"
def out(n): return f"{W}/out-{n}"
def docs_dir(): return f"{W}/docs"
def exists(p): return os.path.exists(p)
def claim(key):
    try: os.mkdir(f"{W}/claims/{key}"); return True
    except FileExistsError: return False


def sh(cmd, logfile, env=None, check=False):
    e = dict(os.environ); e.update(env or {})
    with open(logfile, "a") as f: r = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT, env=e, stdin=subprocess.DEVNULL)
    if check and r.returncode: raise RuntimeError(f"{cmd[:3]} rc {r.returncode}")
    return r.returncode


# ------------------------------------------------------------------------------------------------------------- servers
class Server:
    def __init__(self, lane): self.lane = lane; self.cards, self.port = LANES[lane]; self.proc = None

    def alive(self): return self.proc is not None and self.proc.poll() is None

    def ensure(self):
        if self.alive(): return
        y = f"{W}/gen{self.lane}.yaml"
        open(y, "w").write(f"""server:
  host: 127.0.0.1
  port: {self.port}
memory:
  host-headroom-mib: 8192
models:
  iq6r:
    model: {IQ6R}
    tp: 2
    tp-wire: wht6
    kv-cache-dtype: i8
    max-model-len: 135168
    max-num-seqs: 12
    checkpoint-slots: 32
    prefix-cache-mib: 16384
    mm-max-patches: 0
""")
        env = dict(os.environ, LD_LIBRARY_PATH=LIBS, RADIANCE_HOME=GEN_RH, ROCR_VISIBLE_DEVICES=self.cards)
        self.proc = subprocess.Popen([GEN_RB, "--config", y], stdout=open(f"{W}/logs/serve{self.lane}.log", "a"), stderr=subprocess.STDOUT, env=env, stdin=subprocess.DEVNULL)
        log(f"lane {self.lane}: generation server starting (pid {self.proc.pid}, cards {self.cards}, port {self.port})")
        t0 = time.time()
        while time.time() - t0 < 1500:
            if ABORT.is_set(): raise RuntimeError("abort")
            if not self.alive(): raise RuntimeError(f"lane {self.lane}: server died at start")
            try:
                urllib.request.urlopen(f"http://127.0.0.1:{self.port}/health", timeout=5).read(); break
            except Exception: time.sleep(10)
        else: raise RuntimeError(f"lane {self.lane}: server not up in 25 min")
        log(f"lane {self.lane}: generation server up after {(time.time() - t0) / 60:.1f} min")

    def stop(self):
        if self.proc is None: return
        if self.alive():
            self.proc.terminate()
            try: self.proc.wait(60)
            except subprocess.TimeoutExpired: self.proc.kill(); self.proc.wait()
        self.proc = None; log(f"lane {self.lane}: generation server stopped")


SRV = {l: Server(l) for l in LANES}


# ---------------------------------------------------------------------------------------------------------------- generation
def maybe_complete(n):
    o = out(n)
    if exists(f"{o}/gen.done"): return True
    if exists(f"{o}/closed") and not any(f.startswith("running-") for f in os.listdir(o)):
        want = sum(1 for _ in open(f"{render(n)}/cuts.jsonl")); have = sum(1 for f in os.listdir(f"{o}/gen") if f.endswith(".json"))
        if SETS[n]["target"] == 0 and have != want: return False
        open(f"{o}/gen.done", "w").close(); log(f"generation {n} complete: {have} cuts, {sum(int(l.split()[1]) for l in open(f'{o}/gen.tok'))} tokens"); return True
    return False


def wait_gen_done(n):
    while not maybe_complete(n):
        if ABORT.is_set(): raise RuntimeError("abort")
        time.sleep(20)


def gen_stage(lane, names):
    todo = [n for n in names if not exists(f"{out(n)}/gen.done")]
    if not todo: return
    srv = SRV[lane]
    for attempt in range(3):
        srv.ensure(); procs = []
        for n in todo:
            os.makedirs(f"{out(n)}/claims", exist_ok=True); open(f"{out(n)}/running-{lane}", "w").close()
            cmd = [PY, "-I", f"{C}/gen230.py", render(n), out(n), "--ports", str(srv.port), "--slots", str(GEN_SLOTS[n]), "--target", str(SETS[n]["target"])]
            procs.append((n, subprocess.Popen(cmd, stdout=open(f"{W}/logs/gen-{n}-{lane}.out", "a"), stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL)))
            log(f"lane {lane}: gen230 {n} started (slots {GEN_SLOTS[n]})")
        rcs = {}
        for n, p in procs:
            rcs[n] = p.wait(); os.remove(f"{out(n)}/running-{lane}")
        log(f"lane {lane}: gen230 ended rc {rcs}")
        for n in todo: maybe_complete(n)
        if all(r == 0 for r in rcs.values()): return
        if ABORT.is_set(): raise RuntimeError("abort")
        log(f"lane {lane}: a generator failed (attempt {attempt}); restarting the server")
        srv.stop(); time.sleep(30)
    raise RuntimeError(f"lane {lane}: generators failed 3 times")


# -------------------------------------------------------------------------------------------------------------------- docs / record
def build_docs(n):
    cj = f"{docs_dir()}/{n}.chunks.json"
    if exists(cj): return
    if claim(f"docs-{n}"):
        os.makedirs(docs_dir(), exist_ok=True)
        rc = sh([PY, "-I", f"{C}/docs230.py", n, render(n), out(n), docs_dir(), "--chunks", str(SETS[n]["chunks"]), "--tok", MODEL], f"{W}/logs/docs-{n}.out")
        log(f"docs230 {n} rc {rc}")
        if rc: ABORT.set(); raise RuntimeError(f"docs230 {n} failed")
    while not exists(cj):
        if ABORT.is_set(): raise RuntimeError("abort")
        time.sleep(15)


def chunks_of(n): return json.load(open(f"{docs_dir()}/{n}.chunks.json"))


def rec_chunk(cards, tp, n, ch, tag):
    g = f"{W}/rec/{n}-c{ch['k']}"
    if exists(f"{g}/.done"): return True
    os.makedirs(f"{W}/rec", exist_ok=True); shutil.rmtree(g + ".part", ignore_errors=True)
    while int(subprocess.check_output(["df", "-BG", "--output=avail", W]).split()[-1].decode().strip("G")) < int(E("W230_MIN_GB", 120)):
        log("disk < 120 GB free: waiting"); time.sleep(300)
        if ABORT.is_set(): raise RuntimeError("abort")
    mml = (ch["max_tokens"] + 64 + 255) // 256 * 256; seqs = 1 if ch["max_tokens"] > 20000 else (2 if tp == 2 else 4)
    y = f"{W}/rec/{n}-c{ch['k']}.{tag}.yaml"
    open(y, "w").write(f"""memory:
  host-headroom-mib: 8192
models:
  {n.replace('-', '_')}_c{ch['k']}:
    model: {MODEL}
    tp: {tp}
    kv-cache-dtype: bf16
    max-model-len: {mml}
    max-num-seqs: {seqs}
    kld-record: {g}.part
    kld-corpus: {docs_dir()}/{ch['file']}
    kld-top: 512
""")
    s = time.time(); log(f"{tag}: recording {n} chunk {ch['k']} ({ch['docs']} docs, {ch['tokens']} tokens, max {ch['max_tokens']}, TP{tp}, max-model-len {mml}, seqs {seqs})")
    rc = sh([REC_RB, "--config", y], f"{W}/logs/rec-{n}-c{ch['k']}-{tag}.log",
            env={"LD_LIBRARY_PATH": LIBS, "RADIANCE_HOME": REC_RH, "ROCR_VISIBLE_DEVICES": cards})
    ok = rc == 0 and exists(f"{g}.part/kld.json")
    log(f"{tag}: record {n} chunk {ch['k']} rc {rc} in {(time.time() - s) / 60:.1f} min ({ch['tokens'] / max(time.time() - s, 1):.0f} tok/s)")
    if ok:
        open(f"{g}.part/.done", "w").close(); os.replace(g + ".part", g)
    return ok


def maybe_merge(n):
    s = SETS[n]
    if exists(f"{s['final']}/.done") or not all(exists(f"{W}/rec/{n}-c{ch['k']}/.done") for ch in chunks_of(n)): return
    if not claim(f"merge-{n}"): return
    def job():
        os.makedirs(os.path.dirname(s["corpus_out"]), exist_ok=True)
        cmd = [PY, "-I", f"{C}/merge230.py", n, docs_dir(), f"{W}/rec", s["final"], "--corpus-out", s["corpus_out"]]
        if s["mask"]: os.makedirs(os.path.dirname(s["mask"]), exist_ok=True); cmd += ["--mask-out", s["mask"]]
        rc = sh(cmd, f"{W}/logs/merge-{n}.out"); log(f"merge230 {n} rc {rc}: {open(f'{W}/logs/merge-{n}.out').read().strip().splitlines()[-1][:200]}")
        if rc: ABORT.set(); return
        rc = sh([PY, "-I", f"{C}/check230.py", s["final"], s["corpus_out"], MODEL], f"{W}/logs/check-{n}.out")
        log(f"check230 {n} rc {rc}: {open(f'{W}/logs/check-{n}.out').read().strip().splitlines()[-1][:400]}")
        if rc: ABORT.set(); return
        if rc == 0:
            for ch in chunks_of(n): shutil.rmtree(f"{W}/rec/{n}-c{ch['k']}", ignore_errors=True)   # the merged golden holds the data
    t = threading.Thread(target=job); t.start(); MERGES.append(t)


MERGES = []


def rec_loop(lane, names):
    SRV[lane].stop(); cards = LANES[lane][0]
    for n in names:
        wait_gen_done(n); build_docs(n)
        for ch in chunks_of(n):
            if ABORT.is_set(): raise RuntimeError("abort")
            g = f"{W}/rec/{n}-c{ch['k']}"
            if exists(f"{g}/.done") or exists(f"{g}.tp4"): continue
            if not claim(f"rec-{n}-c{ch['k']}"): continue
            if rec_chunk(cards, 2, n, ch, f"lane {lane} TP2"): maybe_merge(n)
            else: open(f"{g}.tp4", "w").close(); log(f"lane {lane}: {n} chunk {ch['k']} failed on TP2: queued for TP4")


def tp4_phase():
    for n in SETS:
        for ch in chunks_of(n):
            g = f"{W}/rec/{n}-c{ch['k']}"
            if exists(f"{g}.tp4") and not exists(f"{g}/.done"):
                if rec_chunk("0,1,2,3", 4, n, ch, "all four cards TP4"): os.remove(f"{g}.tp4"); maybe_merge(n)
                else: ABORT.set(); raise RuntimeError(f"{n} chunk {ch['k']} failed on TP4 too")


# ------------------------------------------------------------------------------------------------------------------------ lanes
def lane_main(lane):
    try:
        gen_stage(lane, ["t2-judge", "t2"])
        if lane == "A":                                       # lane A records set 2 while B generates set 1
            rec_loop("A", ["t2-judge", "t2"])
        gen_stage(lane, ["t1-judge", "t1"])
        rec_loop(lane, ["t2-judge", "t2"])                    # a lane without set-1 sessions left helps with any set-2 chunk still open
        rec_loop(lane, ["t1-judge", "t1"])
        SRV[lane].stop()
    except Exception as e:
        log(f"lane {lane} FAILED: {type(e).__name__}: {e}"); ABORT.set(); SRV[lane].stop()
        raise


def progress():
    while not DONE.is_set():
        DONE.wait(600)
        parts = []
        for n in SETS:
            o = out(n)
            try:
                tok = sum(int(l.split()[1]) for l in open(f"{o}/gen.tok")); cuts = sum(1 for _ in open(f"{o}/gen.tok"))
            except FileNotFoundError: tok = cuts = 0
            tot = sum(1 for _ in open(f"{render(n)}/cuts.jsonl"))
            parts.append(f"{n}: gen {cuts}/{tot} cuts {tok} tok{' DONE' if exists(o + '/gen.done') else ''}{' MERGED' if exists(SETS[n]['final'] + '/.done') else ''}")
        log("progress | " + " | ".join(parts))


DONE = threading.Event()


def main():
    os.makedirs(f"{W}/logs", exist_ok=True); os.makedirs(f"{W}/claims", exist_ok=True)
    shutil.rmtree(f"{W}/claims", ignore_errors=True); os.makedirs(f"{W}/claims")
    for n in SETS:
        o = out(n); os.makedirs(f"{o}/gen", exist_ok=True)
        if not exists(f"{o}/gen.done"):
            shutil.rmtree(f"{o}/claims", ignore_errors=True)
            for f in os.listdir(o):
                if f.startswith("running-") or f == "closed": os.remove(f"{o}/{f}")
    log(f"chain230 start (pid {os.getpid()})")
    threading.Thread(target=progress, daemon=True).start()
    ths = {l: threading.Thread(target=lane_main, args=(l,)) for l in LANES}
    for t in ths.values(): t.start(); time.sleep(5)
    for t in ths.values(): t.join()
    if ABORT.is_set(): log("chain230 aborted"); sys.exit(1)
    try: tp4_phase()
    except Exception as e: log(f"tp4 phase FAILED: {e}"); sys.exit(1)
    for t in MERGES: t.join()
    for n in SETS:
        maybe_merge(n)
    for t in MERGES: t.join()
    bad = [n for n in SETS if not exists(f"{SETS[n]['final']}/.done")]
    if bad: log(f"chain230 incomplete: not merged {bad}"); sys.exit(1)
    open(f"{W}/chain.done", "w").close(); log("chain230 done"); DONE.set()


if __name__ == "__main__":
    main()
