#!/usr/bin/env python3
"""ukisai.py PARQUET OUTDIR [--tokens N] [--cap T] [--seed S] -- the public Qwen3.8-27B agent traces
(HF ukisai/Qwen3.8-27B-multi-turn-agent-sft, Apache-2.0: 15.2k Terminus-2 sessions generated by Qwen3.8-27B FP16,
nl2bash + InferredBugs tasks, thinking kept) rendered with Qwen's chat template ("<|im_start|>role\\ncontent<|im_end|>\\n",
the assistant's <think> kept as in Qwen3.8's preserved-thinking default), tokenized, each session cut to its first CAP
tokens (default 8192), stratified by task family, until N tokens (default 2.3M). Writes OUTDIR/{kld.json, tokens.i32,
gen.u8} (gen = the assistant turns' tokens incl. <|im_end|>: what the model wrote) like xcorp/xgold.py, plus
OUTDIR/corpus.jsonl ({prompt, source, score_from: 0}: a radiance --kld-corpus for a 27B golden) and pools.json (all "qad")."""
import argparse, json, os, random
import numpy as np, pyarrow.parquet as pq
from transformers import AutoTokenizer
ap = argparse.ArgumentParser(); ap.add_argument("parquet"); ap.add_argument("out")
ap.add_argument("--tokens", type=int, default=2_300_000); ap.add_argument("--cap", type=int, default=8192)
ap.add_argument("--seed", type=int, default=1105); ap.add_argument("--skip", type=int, default=0, help="skip the first N picks (fresh sets)")
ap.add_argument("--tokenizer", default=os.environ.get("XCORP_TOKENIZER", "/data/models/qwen38-27b-bf16"))
a = ap.parse_args(); tok = AutoTokenizer.from_pretrained(a.tokenizer)
rows = pq.read_table(a.parquet).to_pylist(); rng = random.Random(a.seed)
fam = {}
for i, r in enumerate(rows): fam.setdefault(r["task"].split("-")[0], []).append(i)
for v in fam.values(): rng.shuffle(v)
order = []; its = {k: iter(v) for k, v in fam.items()}
while its:
    for k in list(its):
        try: order.append(next(its[k]))
        except StopIteration: del its[k]
order = order[a.skip:]
os.makedirs(a.out, exist_ok=True); docs, T, G, n, row0 = [], [], [], 0, 0; cj = open(f"{a.out}/corpus.jsonl", "w")
for i in order:
    r = rows[i]; ids, m, text = [], [], ""
    for msg in r["conversations"]:
        head = tok(f"<|im_start|>{msg['role']}\n", add_special_tokens=False)["input_ids"]
        body = tok(msg["content"] + "<|im_end|>\n", add_special_tokens=False)["input_ids"]
        ids += head + body; m += [0] * len(head) + [1 if msg["role"] == "assistant" else 0] * len(body)
        text += f"<|im_start|>{msg['role']}\n{msg['content']}<|im_end|>\n"
    ids, m = ids[:a.cap], m[:a.cap]
    if sum(m) < 64: continue
    T.append(np.asarray(ids, np.int32)); G.append(np.asarray(m[1:], np.uint8))
    docs.append({"source": "ukisai/" + r["task"].split("-")[0], "category": "agentic", "tokens": len(ids), "score_from": 0,
                 "row0": row0, "task": r["task"], "orig": i}); row0 += len(ids) - 1; n += len(ids)
    cj.write(json.dumps({"prompt": tok.decode(ids), "source": "ukisai/" + r["task"].split("-")[0], "score_from": 0}) + "\n")
    if n >= a.tokens: break
np.concatenate(T).tofile(f"{a.out}/tokens.i32"); np.concatenate(G).tofile(f"{a.out}/gen.u8")
json.dump({"format": "radiance-kld-top-1", "top": 512, "n_vocab": 248320, "rows": row0, "docs": docs}, open(f"{a.out}/kld.json", "w"))
json.dump({"pool": ["qad"] * len(docs)}, open(f"{a.out}/pools.json", "w"))
print("UKISAI DONE", len(docs), "docs", n, "tokens", int(np.concatenate(G).sum()), "assistant rows")
