#!/usr/bin/env python3
"""report.py O [--pick] -- d1113 (README.md): reads O/result.txt ("pair A -> B" lines of pcmp.py, "jfit" summary and
"repro" lines) and applies the README's rules. Markdown to stdout. --pick: the stage-1 family picks instead, as
"attn=V", "gdn=V" (empty = the family is null at the trunk) and "final=1" once every screen pair of K3 / K2 seeds 0-2
is in (run.sh only writes pick.txt then)."""
import math, re, sys

O = sys.argv[1]; PICK = "--pick" in sys.argv
P, JF, REPRO, CTRL = {}, {}, [], []
for l in open(f"{O}/result.txt"):
    m = re.search(r"pair (\S+) -> (\S+): \"ratio\": ([0-9.]+), \"diff\": [0-9.e+-]+, \"se\": [0-9.e+-]+, \"z\": ([0-9.e+-]+)", l)
    if m: P[(m[1], m[2])] = (float(m[3]), float(m[4])); continue
    m = re.search(r"jfit (\S+): (.*)", l)
    if m:
        for v, kind, b, f, r in re.findall(r"SUMMARY (\w+): (\w+) mean held rel resid ([0-9.e+-]+) -> ([0-9.e+-]+) \(([0-9.]+)\)", m[2]):
            JF[(m[1], v)] = (kind, float(b), float(f), float(r))
        continue
    if " repro " in l: REPRO.append(l.split(" ", 1)[1].strip())
    if " control " in l: CTRL.append(l.split(" ", 1)[1].strip())

sfx = lambda s: "" if s == 0 else f"_s{s}"
ATT, GDN = ("qk", "vg", "at", "aw"), ("gz", "gd", "dw")

def stat(fa, fb, seeds):
    """fa(s), fb(s) -> tags; per-seed (seed, ratio, z), n, geo, mean log, SE over seeds"""
    rs = [(s, *P[(fa(s), fb(s))]) for s in seeds if (fa(s), fb(s)) in P]
    if not rs: return None
    lg = [math.log(r) for _, r, _ in rs]; n = len(lg); m = sum(lg) / n
    se = (sum((x - m) ** 2 for x in lg) / (n - 1)) ** 0.5 / n ** 0.5 if n > 1 else float("nan")
    return dict(rs=rs, n=n, geo=math.exp(m), mlog=m, se=se, lt1=all(r < 1 for _, r, _ in rs), gt1=all(r > 1 for _, r, _ in rs))

def fmt(st):
    if st is None: return "— | — | — | —"
    return (" ".join(f"s{s} {r:.4f} ({z:+.1f})" for s, r, z in st["rs"]) +
            f" | {st['n']} | **{st['geo']:.4f}** | {st['mlog']:+.4f} ± {st['se']:.4f}")

def scr(k, v, seeds):   # screen: variant / e_swj on the fit golden
    return stat(lambda s: f"fit-k{k}e{sfx(s)}_swj", lambda s: f"fit-k{k}j{v}{sfx(s)}", seeds)

def picks(seeds=(0, 1, 2)):
    out, final = {}, True
    for fam, vs in (("attn", ATT), ("gdn", GDN)):
        best = None
        for v in vs:
            a, b = scr(3, v, seeds), scr(2, v, seeds)
            if not a or not b or a["n"] < len(seeds) or b["n"] < len(seeds): final = False; continue
            if a["geo"] <= 0.995 and b["geo"] <= 0.995:
                ml = a["mlog"] + b["mlog"]
                if best is None or ml < best[1]: best = (v, ml)
        out[fam] = best[0] if best else ""
    return out, final

if PICK:
    pk, final = picks()
    print(f"attn={pk['attn']}\ngdn={pk['gdn']}\nfinal={int(final)}"); sys.exit(0)

def verdict(arm, seeds):
    s = {k: stat(lambda x: f"k{k}st{sfx(x)}", lambda x: f"k{k}{arm}{sfx(x)}", seeds) for k in (3, 2)}
    v = {k: stat(lambda x: f"vf-k{k}st{sfx(x)}", lambda x: f"vf-k{k}{arm}{sfx(x)}", seeds) for k in (3, 2)}
    if any(s[k] is None for k in (3, 2)): return "missing", s, v
    keep = {k: (v[k] is not None and s[k]["mlog"] < 0 and v[k]["mlog"] <= 2 / 3 * s[k]["mlog"]) for k in (3, 2)}
    if all(s[k]["geo"] <= 0.98 and s[k]["lt1"] and keep[k] for k in (3, 2)): w = "adopt-for-27B"
    elif any(s[k]["geo"] >= 1.01 and s[k]["gt1"] for k in (3, 2)): w = "harmful"
    elif all(s[k]["lt1"] and s[k]["geo"] <= 0.995 for k in (3, 2)): w = "real but below the bar"
    else: w = "null"
    if any(s[k]["n"] < len(seeds) for k in (3, 2)): w += " (interim)"
    return w, s, v

print("# d1113 report (generated by report.py; rules in README.md)\n")
print("## Stage 1 · screen (g08-fit1; variant / edy + swj, codes and swj shared)\n")
print("| K | variant | per seed: ratio (z) | n | geo | mean log ± SE |\n|---|---|---|---|---|---|")
for k in (3, 2, 4):
    for v in ATT + GDN:
        print(f"| K{k} | {v} | {fmt(scr(k, v, (0, 1, 2)))} |")
print()
print("Seeds 3–4 (robustness, K3 / K2, seeds 0–4):\n")
print("| K | variant | per seed | n | geo | mean log ± SE |\n|---|---|---|---|---|---|")
for k in (3, 2):
    for v in ATT + GDN:
        st = scr(k, v, (0, 1, 2, 3, 4))
        if st and st["n"] > 3: print(f"| K{k} | {v} | {fmt(st)} |")
print()
pk, final = picks()
print(f"**Family picks** (rule: lowest K3 + K2 mean log among variants with geo ≤ 0.995 at both): attention = "
      f"`{pk['attn'] or 'none (null)'}`, GDN = `{pk['gdn'] or 'none (null)'}`{'' if final else ' (interim: screen incomplete)'}\n")
print("**Solver check** (search; Adam gate / up fit mA / swiglufit swj, both on the trunk edy; README: 0.98–1.02 = equivalent):\n")
print("| K | per seed | n | geo | mean log ± SE |\n|---|---|---|---|---|")
for k in (3, 2):
    print(f"| K{k} | {fmt(stat(lambda s: f'k{k}e{sfx(s)}_swj', lambda s: f'k{k}jmA{sfx(s)}', (0, 1, 2)))} |")
print()
if JF:
    print("Held-out relative residual of the block output (jfit, qad held windows; ratio fit / base, mean over layers):\n")
    bases = sorted({b for b, _ in JF}, key=lambda b: (b[:2], b))
    print("| base | " + " | ".join(ATT + GDN + ("mA",)) + " |\n|---|" + "---|" * 8)
    for b in bases:
        print(f"| {b} | " + " | ".join(f"{JF[(b, v)][3]:.3f}" if (b, v) in JF else "—" for v in ATT + GDN + ("mA",)) + " |")
    print()
if REPRO or CTRL:
    print("Reproduction / control reuse:\n"); [print(f"- {x}") for x in REPRO + CTRL]; print()

print("## Stage 2 · full stack (arm / st; search decides, verify = overfitting check)\n")
for arm, lab in (("fc", "combined"), ("fa", "attention pick"), ("fg", "GDN pick")):
    w, s, v = verdict(arm, (0, 1, 2))
    if w == "missing" and not any(stat(lambda x: f"k4st{sfx(x)}", lambda x: f"k4{arm}{sfx(x)}", (0, 1, 2)) for _ in [0]): 
        print(f"### {arm} ({lab}): not run / no data\n"); continue
    w5, s5, _ = verdict(arm, (0, 1, 2, 3, 4))
    frag = ""
    if all(s5[k] and s5[k]["n"] == 5 for k in (3, 2)) and w5.split(" (")[0] != w.split(" (")[0]: frag = f" — **fragile** (seeds 0–4: {w5})"
    print(f"### {arm} ({lab}): **{w}**{frag}\n")
    print("| K | golden | per seed: ratio (z) | n | geo | mean log ± SE |\n|---|---|---|---|---|---|")
    for k in (3, 2, 4):
        for g, lab2 in (("", "search"), ("vf-", "verify")):
            print(f"| K{k} | {lab2} | {fmt(stat(lambda x: f'{g}k{k}st{sfx(x)}', lambda x: f'{g}k{k}{arm}{sfx(x)}', (0, 1, 2)))} |")
    for k in (3, 2):
        sv, vv = s[k], v[k]
        if sv and vv and sv["mlog"] < 0: print(f"\nK{k} verify keeps {vv['mlog'] / sv['mlog']:.2f} of the search gain (bar ⅔).", end="")
    print("\n")
    for k in (3, 2):
        st = stat(lambda x: f"k{k}st{sfx(x)}", lambda x: f"k{k}{arm}{sfx(x)}", (0, 1, 2, 3, 4))
        if st and st["n"] > 3: print(f"- seeds 0–4, K{k} search: {fmt(st)}")
    k4 = stat(lambda x: f"k4st{sfx(x)}", lambda x: f"k4{arm}{sfx(x)}", (0, 1, 2))
    if k4 and k4["geo"] >= 1.01: print(f"- **K4 flag:** geo {k4['geo']:.4f} ≥ 1.01 (limit to K ≤ 3.5)")
    print()
